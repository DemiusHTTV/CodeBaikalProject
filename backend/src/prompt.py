"""Сборка промпта для модели — общая для консоли (ask.py) и HTTP API (main.py).

Держим в одном месте, чтобы консоль и веб не разъехались: если правило про
персональные данные поправили здесь, оно поменялось сразу везде.

Три вещи, которые этот файл решает помимо схемы:
1. NO_SQL — модель должна уметь отказаться. Без этого на вопрос "2+2" она
   честно генерирует "SELECT 2 + 2", запрос отрабатывает и пользователь видит
   бессмысленное "?column? = 4" вместо внятного "я про базу университета".
2. Реальные значения справочников — модель не видит содержимое таблиц и
   угадывает строки. Из-за этого "факультет ИТ" превращалось то в
   ILIKE '%ИТ%' (ловит "вычислительная" — там есть "ит"), то в точное
   name = 'информационных технологий' (0 строк). Даём ей точные названия.
3. Правила по роли — что можно выводить, а что только агрегатами.
"""
from __future__ import annotations

from .roles import RolePolicy
from .schema_context import build_schema_prompt, parse_tables

# Два разных отказа: вопрос вообще не про базу — и вопрос про базу, но данные
# закрыты для этой роли. Пользователю нужно объяснить это по-разному, поэтому
# маркера тоже два, а не один общий.
OFFTOPIC_MARKER = "NO_SQL_OFFTOPIC"
FORBIDDEN_MARKER = "NO_SQL_FORBIDDEN"

_BASE_RULES = """Ты переводишь вопрос сотрудника университета в один SQL-запрос PostgreSQL.

Правила:
- Верни только сам SQL-запрос: без markdown, без пояснений, без точки с запятой.
- Разрешён только SELECT.
- Не пиши SELECT * — перечисляй нужные колонки явно.
- Для поиска по названиям используй точные значения из справочников ниже.
  Если подходящего значения в списке нет — бери ILIKE с достаточно длинным
  фрагментом, чтобы он не совпал с посторонним словом.

Результат читает человек, а не программа:
- НИКОГДА не выводи колонки-идентификаторы (discipline_id, teacher_id,
  group_id, student_id и любые другие *_id). Вместо идентификатора присоедини
  нужную таблицу и выведи название: вместо grades.discipline_id —
  disciplines.name. «5» пользователю ничего не говорит, «Базы данных» — говорит.
- Каждой колонке результата дай понятный псевдоним по-русски через AS:
  AS "Дисциплина", AS "Средний балл", AS "Количество студентов".
- Дробные числа округляй: ROUND(AVG(grade), 2), а не голый AVG(grade).

Как связаны таблицы (важно, иначе запрос вернёт пусто):
- «Какие дисциплины у группы/студента» — это teacher_disciplines
  (связка группа-дисциплина-преподаватель). Через неё же считается нагрузка.
- schedule — это КОНКРЕТНЫЕ пары в сетке расписания (день недели, время,
  аудитория). Используй её только когда спрашивают про время, день или
  аудиторию. Для вопроса «какие у меня дисциплины» она не подходит.
- Студент связан с дисциплинами так:
  students -> groups_ -> teacher_disciplines -> disciplines."""

_NO_SQL_RULE = f"""- Если вопрос не относится к данным этой базы (арифметика, погода, общие
  знания, просьбы что-то изменить) — верни ровно одно слово {OFFTOPIC_MARKER}
  и ничего больше. Не придумывай SQL ради ответа.
- Если вопрос про данные университета, но ответить можно только выведя данные,
  которые тебе запрещены правилами ниже — верни ровно одно слово
  {FORBIDDEN_MARKER} и ничего больше."""


ANSWER_PROMPT = """Ты — ассистент университета. Тебе дают вопрос сотрудника и
таблицу с ответом из базы данных. Перескажи результат одним-двумя предложениями
на русском языке.

Правила:
- Опирайся ТОЛЬКО на цифры и названия из таблицы. Ничего не додумывай.
- Не пересказывай таблицу построчно, если строк много — назови главное
  (сколько всего, кто в лидерах, какой разброс).
- Не упоминай SQL, таблицы базы и служебные слова вроде «запрос вернул».
  Пиши так, как ответил бы коллега.
- Если таблица пустая — скажи, что подходящих записей не нашлось.
- Никаких вступлений вроде «Конечно!» — сразу по делу."""


def _reference_values(policy: RolePolicy) -> str:
    """Точные названия факультетов и направлений — чтобы модель не угадывала строки."""
    lines = []
    if "faculties" in policy.allowed_tables:
        lines.append(
            "Факультеты (faculties.name): 'Факультет информационных технологий', "
            "'Экономический факультет', 'Юридический факультет', "
            "'Факультет менеджмента', 'Гуманитарный факультет'"
        )
    if "directions" in policy.allowed_tables:
        lines.append(
            "Направления (directions.name): 'Информатика и вычислительная техника', "
            "'Программная инженерия', 'Экономика', 'Финансы и кредит', "
            "'Юриспруденция', 'Менеджмент', 'Лингвистика'"
        )
    if not lines:
        return ""
    return "Реальные значения справочников:\n" + "\n".join(f"- {line}" for line in lines)


def build_sql_prompt(policy: RolePolicy, own_student_id: int | None = None) -> str:
    tables = [t for t in parse_tables() if t.name in policy.allowed_tables]
    parts = [build_schema_prompt(tables), _BASE_RULES, _NO_SQL_RULE]

    if policy.allow_raw_pii:
        parts.append("- Данные студентов и абитуриентов можно выводить как есть, включая ФИО.")
    else:
        parts.append(
            "- ФИО студентов и абитуриентов выводить нельзя. Фильтровать по ним можно, "
            "если результат — агрегат (COUNT/AVG/SUM), например «сколько студентов "
            "на букву А»."
        )

    if own_student_id is not None:
        parts.append(
            f"- Текущий пользователь — студент с student_id = {own_student_id}. Если вопрос "
            f"про «меня»/«мою успеваемость»/«мои дисциплины» — фильтруй "
            f"WHERE student_id = {own_student_id}. Данные другого student_id запрашивать нельзя."
        )

    reference = _reference_values(policy)
    if reference:
        parts.append(reference)

    return "\n\n".join(parts)
